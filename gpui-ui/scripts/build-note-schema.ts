// Generate src/notes/native/zotero-schema.gen.js: Zotero's note schema (vendor/note-editor/src/core/schema: its nodes, marks and
// HTML parse rules), its Metadata class, its citation formatter and the prosemirror-model DOMParser that reads note HTML with them,
// bundled into one ES module the app imports like any other file (the AOT build packs it; nothing is read from disk at run time).
// Re-run after updating vendor/note-editor:
//   bun scripts/build-note-schema.ts            (needs vendor/note-editor with its node_modules: bash note-host/build.sh)
// The output is committed, so building the app needs no note-editor checkout.
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ED = fileURLToPath(new URL("../../vendor/note-editor/", import.meta.url));
const SCHEMA = join(ED, "src/core/schema");
const OUT = fileURLToPath(new URL("../src/notes/native/zotero-schema.gen.js", import.meta.url));
if (!existsSync(join(SCHEMA, "index.js")) || !existsSync(join(ED, "node_modules")))
	throw new Error(`${ED}: no note-editor checkout with node_modules (run bash note-host/build.sh)`);

// the prosemirror-model the schema itself imports: one copy in the bundle, so the schema's types and the parser's agree
const pm = Bun.resolveSync("prosemirror-model", SCHEMA);
const commit = (() => {
	try {
		return execFileSync("git", ["-C", ED, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
	} catch {
		return "unknown";
	}
})();

const dir = mkdtempSync(join(tmpdir(), "zn-note-schema-"));
const entry = join(dir, "entry.js");
const p = (f: string) => JSON.stringify(f.replace(/\\/g, "/"));
writeFileSync(
	entry,
	[
		`export { schema } from ${p(join(SCHEMA, "index.js"))};`,
		`export { default as Metadata } from ${p(join(SCHEMA, "metadata.js"))};`,
		`export { formatCitationItem } from ${p(join(ED, "src/core/utils.js"))};`,
		`export { DOMParser } from ${p(pm)};`,
	].join("\n"),
);
try {
	const r = await Bun.build({
		entrypoints: [entry],
		target: "bun",
		format: "esm",
		minify: true,
		// the note-editor's webpack defines; its fluent strings are plain text files
		define: { __BUILD__: JSON.stringify("web") },
		loader: { ".ftl": "text" },
	});
	if (!r.success) throw new AggregateError(r.logs, "bundling the note schema failed");
	const code = await r.outputs[0]!.text();
	const header =
		`// GENERATED by gpui-ui/scripts/build-note-schema.ts from zotero/note-editor ${commit} (src/core/schema, src/core/utils.js)\n` +
		`// and its prosemirror-model / prosemirror-tables. Do not edit. zotero-note-editor is (c) Corporation for Digital Scholarship,\n` +
		`// AGPL-3.0 (vendor/note-editor/COPYING); ProseMirror is MIT.\n` +
		`// biome-ignore-all lint: generated\n/* eslint-disable */\n`;
	writeFileSync(OUT, header + code);
	console.log(`wrote ${OUT} (${(code.length / 1024).toFixed(0)} KB, note-editor ${commit})`);
} finally {
	rmSync(dir, { recursive: true, force: true });
}
